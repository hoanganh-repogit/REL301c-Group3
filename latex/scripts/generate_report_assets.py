"""Generate publication figures from training and cross-level evaluation CSVs."""
from __future__ import annotations

import csv
import math
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / '.tools/presentation'))

import matplotlib.pyplot as plt
import numpy as np


ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "latex/generated"
TRAINING_CSV = ROOT / "results/level4_continuous_dqn/seed_0/episodes.csv"
EVALUATION_CSV = ROOT / "results/cross_level_evaluation/episodes.csv"

COLORS = {
    "best_dqn": "#1f77b4",
    "final_dqn": "#ff7f0e",
    "random": "#7f7f7f",
}

TARGETS = {
    "level1": 25,
    "level2": 35,
    "level3": 50,
    "level4": None,
    "level5": 100,
    "level6": 150,
}


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open("r", encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def save(fig: plt.Figure, name: str) -> None:
    OUTPUT.mkdir(parents=True, exist_ok=True)
    fig.savefig(OUTPUT / f"{name}.pdf", bbox_inches="tight")
    fig.savefig(OUTPUT / f"{name}.png", dpi=220, bbox_inches="tight")
    plt.close(fig)


def wilson_interval(successes: int, total: int, z: float = 1.95996398454005) -> tuple[float, float]:
    """Return a two-sided Wilson score interval as percentages."""
    proportion = successes / total
    denominator = 1 + z**2 / total
    center = (proportion + z**2 / (2 * total)) / denominator
    half_width = (
        z
        * math.sqrt((proportion * (1 - proportion) + z**2 / (4 * total)) / total)
        / denominator
    )
    return 100 * (center - half_width), 100 * (center + half_width)


def main_results_rows() -> None:
    """Generate the LaTeX rows used by the paper's primary results table."""
    rows = read_csv(EVALUATION_CSV)
    output_rows = []
    for level_number in range(1, 7):
        level = f"level{level_number}"
        scores = np.asarray([
            float(row["score"])
            for row in rows
            if row["policy"] == "best_dqn" and row["level"] == level
        ])
        if scores.size == 0:
            raise ValueError(f"No best_dqn evaluation rows found for {level}")

        target = TARGETS[level]
        if target is None:
            success = interval = normalized = "N/A"
        else:
            successes = int(np.count_nonzero(scores >= target))
            low, high = wilson_interval(successes, int(scores.size))
            success = f"{100 * successes / scores.size:.0f}"
            interval = f"{low:.1f}--{high:.1f}"
            normalized = f"{np.minimum(scores / target, 1).mean():.3f}"

        output_rows.append(
            f"    {level_number} & ${scores.mean():.2f}\\pm{scores.std():.2f}$"
            f" & {np.median(scores):.1f} & {np.percentile(scores, 25):.1f}"
            f" & {np.percentile(scores, 75):.1f} & {success} & {interval}"
            f" & {normalized} \\\\"
        )

    OUTPUT.mkdir(parents=True, exist_ok=True)
    (OUTPUT / "main_results_rows.tex").write_text(
        "% Generated by latex/scripts/generate_report_assets.py; do not edit.\n"
        + "\n".join(output_rows)
        + "\n",
        encoding="utf-8",
    )


def training_curve() -> None:
    rows = read_csv(TRAINING_CSV)
    steps = np.asarray([float(row["global_env_step"]) / 1_000_000 for row in rows])
    scores = np.asarray([float(row["score"]) for row in rows])
    rolling = np.asarray([float(row["rolling_mean_score"]) for row in rows])

    fig, ax = plt.subplots(figsize=(7.2, 3.2))
    ax.scatter(steps, scores, s=2, alpha=0.10, color="#7f7f7f", label="Episode score")
    ax.plot(steps, rolling, linewidth=1.5, color=COLORS["best_dqn"],
            label="100-episode rolling mean")
    # The trainer only compares candidates at 250-episode save points.
    candidates = [i for i, row in enumerate(rows)
                  if int(row['episode']) >= 500 and int(row['episode']) % 250 == 0]
    best_index = max(candidates, key=lambda i: rolling[i])
    ax.scatter([steps[best_index]], [rolling[best_index]], s=35,
               color="#d62728", zorder=3, label="Selected checkpoint")
    ax.annotate(
        f"{rolling[best_index]:.2f} at episode {int(rows[best_index]['episode']):,}",
        (steps[best_index], rolling[best_index]),
        xytext=(-90, 18), textcoords="offset points", fontsize=8,
        arrowprops={"arrowstyle": "->", "lw": 0.8},
    )
    ax.set(xlabel="Environment steps (millions)", ylabel="Score")
    ax.grid(alpha=0.25)
    ax.legend(frameon=False, fontsize=8, ncol=3, loc="upper left")
    save(fig, "training_curve")


def score_distributions() -> None:
    rows = read_csv(EVALUATION_CSV)
    levels = [f"level{i}" for i in range(1, 7)]
    values = [
        [float(row["score"]) for row in rows
         if row["policy"] == "best_dqn" and row["level"] == level]
        for level in levels
    ]
    fig, ax = plt.subplots(figsize=(7.2, 3.2))
    plot = ax.boxplot(values, patch_artist=True, showmeans=True,
                      meanprops={"marker": "o", "markerfacecolor": "white",
                                 "markeredgecolor": "black", "markersize": 4})
    for box in plot["boxes"]:
        box.set_facecolor(COLORS["best_dqn"])
        box.set_alpha(0.70)
    ax.set_xticklabels(["L1", "L2", "L3", "L4", "L5", "L6"])
    ax.set(xlabel="Evaluation level", ylabel="Episode score")
    ax.grid(axis="y", alpha=0.25)
    save(fig, "score_distributions")


def checkpoint_comparison() -> None:
    rows = read_csv(EVALUATION_CSV)
    levels = [f"level{i}" for i in range(1, 7)]
    policies = ["best_dqn", "final_dqn", "random"]
    means = defaultdict(list)
    for policy in policies:
        for level in levels:
            scores = [float(row["score"]) for row in rows
                      if row["policy"] == policy and row["level"] == level]
            means[policy].append(float(np.mean(scores)))
    x = np.arange(len(levels))
    width = 0.25
    fig, ax = plt.subplots(figsize=(7.2, 3.2))
    for offset, policy in zip([-width, 0, width], policies):
        label = {"best_dqn": "Best DQN", "final_dqn": "Final DQN",
                 "random": "Random"}[policy]
        ax.bar(x + offset, means[policy], width, label=label, color=COLORS[policy])
    ax.set_xticks(x, ["L1", "L2", "L3", "L4", "L5", "L6"])
    ax.set(xlabel="Evaluation level", ylabel="Mean score")
    ax.grid(axis="y", alpha=0.25)
    ax.legend(frameon=False, fontsize=8)
    save(fig, "checkpoint_comparison")


def failure_modes() -> None:
    rows = read_csv(EVALUATION_CSV)
    levels = [f"level{i}" for i in range(1, 7)]
    outcomes = ["target_reached", "timeout", "self", "wall", "obstacle"]
    labels = ["Target reached", "Timeout", "Self", "Wall", "Obstacle"]
    colors = ["#2ca02c", "#9467bd", "#d62728", "#8c564b", "#ff7f0e"]
    rates = {outcome: [] for outcome in outcomes}
    for level in levels:
        level_rows = [row for row in rows
                      if row["policy"] == "best_dqn" and row["level"] == level]
        for outcome in outcomes:
            rates[outcome].append(
                sum(row["outcome"] == outcome for row in level_rows) / len(level_rows)
            )
    fig, ax = plt.subplots(figsize=(7.2, 3.2))
    bottom = np.zeros(len(levels))
    for outcome, label, color in zip(outcomes, labels, colors):
        values = np.asarray(rates[outcome])
        ax.bar(range(len(levels)), values, bottom=bottom, label=label, color=color)
        bottom += values
    ax.set_xticks(range(len(levels)), ["L1", "L2", "L3", "L4", "L5", "L6"])
    ax.set(xlabel="Evaluation level", ylabel="Outcome rate", ylim=(0, 1))
    ax.legend(
        loc="upper left",
        bbox_to_anchor=(1.01, 1.0),
        borderaxespad=0,
        frameon=True,
        facecolor="white",
        edgecolor="#c7c7c7",
        framealpha=1.0,
        fontsize=7,
        ncol=1,
    )
    save(fig, "failure_modes")


def main() -> None:
    plt.rcParams.update({
        "font.size": 9,
        "axes.titlesize": 9,
        "axes.labelsize": 9,
        "figure.dpi": 120,
    })
    training_curve()
    score_distributions()
    checkpoint_comparison()
    failure_modes()
    main_results_rows()
    print(f"Generated report assets in {OUTPUT}")


if __name__ == "__main__":
    main()
