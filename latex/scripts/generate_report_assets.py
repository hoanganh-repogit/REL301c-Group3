def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open("r", encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def save(fig: plt.Figure, name: str) -> None:
    OUTPUT.mkdir(parents=True, exist_ok=True)
    fig.savefig(OUTPUT / f"{name}.pdf", bbox_inches="tight")
    fig.savefig(OUTPUT / f"{name}.png", dpi=220, bbox_inches="tight")
    plt.close(fig)


def wilson_interval(successes: int, total: int, z: float = 1.95996398454005) -> tuple[float, float]:
    """Return a two-sided Wilson score interval as percentages."""
    proportion = successes / total
    denominator = 1 + z**2 / total
    center = (proportion + z**2 / (2 * total)) / denominator
    half_width = (
        z
        * math.sqrt((proportion * (1 - proportion) + z**2 / (4 * total)) / total)
        / denominator
    )
    return 100 * (center - half_width), 100 * (center + half_width)


def write_rows(name: str, rows: list[str]) -> None:
    OUTPUT.mkdir(parents=True, exist_ok=True)
    (OUTPUT / name).write_text(
        "% Generated by latex/scripts/generate_report_assets.py; do not edit.\n"
        + "\n".join(rows)
        + "\n",
        encoding="utf-8",
    )


def exact_mcnemar_p(only_first: int, only_second: int) -> float:
    """Two-sided exact McNemar test on the discordant pairs."""
    discordant = only_first + only_second
    if discordant == 0:
        return 1.0
    tail = sum(math.comb(discordant, i) for i in range(min(only_first, only_second) + 1))
    return min(1.0, 2 * tail / 2**discordant)


def holm_adjust(p_values: list[float]) -> list[float]:
    """Holm step-down adjustment, returned in the input order."""
    order = sorted(range(len(p_values)), key=lambda i: p_values[i])
    adjusted = [0.0] * len(p_values)
    running = 0.0
    for rank, index in enumerate(order):
        running = max(running, min(1.0, (len(p_values) - rank) * p_values[index]))
        adjusted[index] = running
    return adjusted


def main_results_rows() -> None:
    """Generate the LaTeX rows used by the paper's primary results table."""
    rows = read_csv(EVALUATION_CSV)
    output_rows = []
    for level_number in range(1, 7):
        level = f"level{level_number}"
        scores = np.asarray([
            float(row["score"])
            for row in rows
            if row["policy"] == "best_dqn" and row["level"] == level
        ])
        if scores.size == 0:
            raise ValueError(f"No best_dqn evaluation rows found for {level}")

        target = TARGETS[level]
        if target is None:
            success = interval = normalized = "N/A"
        else:
            successes = int(np.count_nonzero(scores >= target))
            low, high = wilson_interval(successes, int(scores.size))
            success = f"{100 * successes / scores.size:.0f}"
            interval = f"{low:.1f}--{high:.1f}"
            normalized = f"{np.minimum(scores / target, 1).mean():.3f}"

        output_rows.append(
            f"    {level_number} & ${scores.mean():.2f}\\pm{scores.std():.2f}$"
            f" & {np.median(scores):.1f} & {np.percentile(scores, 25):.1f}"
            f" & {np.percentile(scores, 75):.1f} & {success} & {interval}"
            f" & {normalized} \\\\"
        )

    write_rows("main_results_rows.tex", output_rows)


def timeout_rows() -> None:
    """Show the score at which greedy episodes on target levels time out."""
    rows = read_csv(EVALUATION_CSV)
    output_rows = []
    for level in TARGET_LEVELS:
        level_rows = [row for row in rows
                      if row["policy"] == "best_dqn" and row["level"] == level]
        failures = sum(row["outcome"] != "target_reached" for row in level_rows)
        scores = np.asarray([float(row["score"]) for row in level_rows
                             if row["outcome"] == "timeout"])
        if scores.size == 0:
            median = maximum = early = "--"
        else:
            median = f"{np.median(scores):.0f}"
            maximum = f"{scores.max():.0f}"
            early = f"{np.count_nonzero(scores <= 2)}/{scores.size}"
        output_rows.append(
            f"    {level[-1]} & {failures} & {scores.size} & {median}"
            f" & {maximum} & {early} \\\\"
        )
    write_rows("timeout_rows.tex", output_rows)


def checkpoint_test_rows() -> None:
    """Paired best-versus-final success comparison on identical seeds."""
    rows = read_csv(EVALUATION_CSV)
    results = []
    for level in TARGET_LEVELS:
        success = {
            policy: {row["seed"]: row["success"] == "1" for row in rows
                     if row["policy"] == policy and row["level"] == level}
            for policy in ("best_dqn", "final_dqn")
        }
        seeds = sorted(success["best_dqn"])
        assert seeds == sorted(success["final_dqn"]), f"Seed mismatch on {level}"
        best_only = sum(success["best_dqn"][s] and not success["final_dqn"][s] for s in seeds)
        final_only = sum(success["final_dqn"][s] and not success["best_dqn"][s] for s in seeds)
        results.append((level, sum(success["best_dqn"].values()),
                        sum(success["final_dqn"].values()), best_only, final_only,
                        exact_mcnemar_p(best_only, final_only)))
    adjusted = holm_adjust([result[-1] for result in results])
    output_rows = [
        f"    {level[-1]} & {best} & {final} & {best_only} & {final_only}"
        f" & {p:.3f} & {holm:.3f} \\\\"
        for (level, best, final, best_only, final_only, p), holm in zip(results, adjusted)
    ]
    write_rows("checkpoint_test_rows.tex", output_rows)


def epsilon_rows() -> None:
    """Greedy versus epsilon = 0.01 on the same seeds."""
    output_rows = []
    for row in read_csv(EPSILON_CSV):
        collisions = sum(float(row[name]) for name in ("wall_rate", "obstacle_rate", "self_rate"))
        success = (
            "N/A" if row["success_rate"] == ""
            else f"{100 * float(row['success_rate']):.0f}"
        )
        output_rows.append(
            f"    {row['level'][-1]} & {float(row['epsilon']):g}"
            f" & ${float(row['mean_score']):.2f}\\pm{float(row['std_score']):.2f}$"
            f" & {float(row['median_score']):.0f} & {success}"
            f" & {100 * float(row['timeout_rate']):.0f} & {100 * collisions:.0f} \\\\"
        )
    write_rows("epsilon_rows.tex", output_rows)


def level_layouts() -> None:
    fig, axes = plt.subplots(2, 3, figsize=(7.2, 5.0))
    for ax, (level, filename) in zip(axes.flat, LEVEL_CONFIGS.items()):
        with (ROOT / "configs/envs" / filename).open("r", encoding="utf-8") as handle:
            config = yaml.safe_load(handle)
        height, width = config["size"]
        board = np.zeros((height, width))
        for row, col in config["obstacles"]:
            board[row, col] = 1
        ax.imshow(board, cmap="Greys", vmin=0, vmax=1.25, interpolation="nearest")
        ax.set_xticks(np.arange(-0.5, width, 1), minor=True)
        ax.set_yticks(np.arange(-0.5, height, 1), minor=True)
        ax.grid(which="minor", color="#d9d9d9", linewidth=0.3)
        ax.tick_params(which="both", length=0, labelbottom=False, labelleft=False)
        role = "training" if level == "level4" else "unseen"
        target = config["target_score"] if config["target_score"] is not None else "none"
        ax.set_title(
            f"L{level[-1]} ({role}): {height}x{width}, "
            f"{len(config['obstacles'])} obstacles\ntarget {target}",
            fontsize=8,
            fontweight="bold" if level == "level4" else "normal",
        )
        if level == "level4":
            for spine in ax.spines.values():
                spine.set_edgecolor(COLORS["best_dqn"])
                spine.set_linewidth(2)
    fig.tight_layout()
    save(fig, "level_layouts")


def training_curve() -> None:
    rows = read_csv(TRAINING_CSV)
    steps = np.asarray([float(row["global_env_step"]) / 1_000_000 for row in rows])
    scores = np.asarray([float(row["score"]) for row in rows])
    rolling = np.asarray([float(row["rolling_mean_score"]) for row in rows])

    fig, ax = plt.subplots(figsize=(7.2, 3.2))
    ax.scatter(steps, scores, s=2, alpha=0.10, color="#7f7f7f", label="Episode score")
    ax.plot(steps, rolling, linewidth=1.5, color=COLORS["best_dqn"],
            label="100-episode rolling mean")
    # The trainer only compares candidates at 250-episode save points.
    candidates = [i for i, row in enumerate(rows)
                  if int(row['episode']) >= 500 and int(row['episode']) % 250 == 0]
    best_index = max(candidates, key=lambda i: rolling[i])
    ax.scatter([steps[best_index]], [rolling[best_index]], s=35,
               color="#d62728", zorder=3, label="Selected checkpoint")
    ax.annotate(
        f"{rolling[best_index]:.2f} at episode {int(rows[best_index]['episode']):,}",
        (steps[best_index], rolling[best_index]),
        xytext=(-90, 18), textcoords="offset points", fontsize=8,
        arrowprops={"arrowstyle": "->", "lw": 0.8},
    )
    ax.set(xlabel="Environment steps (millions)", ylabel="Score")
    ax.grid(alpha=0.25)
    ax.legend(frameon=False, fontsize=8, ncol=3, loc="upper left")
    save(fig, "training_curve")


def score_distributions() -> None:
    rows = read_csv(EVALUATION_CSV)
    levels = [f"level{i}" for i in range(1, 7)]
    values = [
        [float(row["score"]) for row in rows
         if row["policy"] == "best_dqn" and row["level"] == level]
        for level in levels
    ]
    fig, ax = plt.subplots(figsize=(7.2, 3.2))
    plot = ax.boxplot(values, patch_artist=True, showmeans=True,
                      meanprops={"marker": "o", "markerfacecolor": "white",
                                 "markeredgecolor": "black", "markersize": 4})
    for box in plot["boxes"]:
        box.set_facecolor(COLORS["best_dqn"])
        box.set_alpha(0.70)
    ax.set_xticklabels(["L1", "L2", "L3", "L4", "L5", "L6"])
    ax.set(xlabel="Evaluation level", ylabel="Episode score")
    ax.grid(axis="y", alpha=0.25)
    save(fig, "score_distributions")


def checkpoint_comparison() -> None:
    rows = read_csv(EVALUATION_CSV)
    levels = [f"level{i}" for i in range(1, 7)]
    policies = ["best_dqn", "final_dqn", "random"]
    means = defaultdict(list)
    for policy in policies:
        for level in levels:
            scores = [float(row["score"]) for row in rows
                      if row["policy"] == policy and row["level"] == level]
            means[policy].append(float(np.mean(scores)))
    x = np.arange(len(levels))
    width = 0.25
    fig, ax = plt.subplots(figsize=(7.2, 3.2))
    for offset, policy in zip([-width, 0, width], policies):
        label = {"best_dqn": "Best DQN", "final_dqn": "Final DQN",
                 "random": "Random"}[policy]
        ax.bar(x + offset, means[policy], width, label=label, color=COLORS[policy])
    ax.set_xticks(x, ["L1", "L2", "L3", "L4", "L5", "L6"])
    ax.set(xlabel="Evaluation level", ylabel="Mean score")
    ax.grid(axis="y", alpha=0.25)
    ax.legend(frameon=False, fontsize=8)
    save(fig, "checkpoint_comparison")


def failure_modes() -> None:
    rows = read_csv(EVALUATION_CSV)
    levels = [f"level{i}" for i in range(1, 7)]
    outcomes = ["target_reached", "timeout", "self", "wall", "obstacle"]
    labels = ["Target reached", "Timeout", "Self", "Wall", "Obstacle"]
    colors = ["#2ca02c", "#9467bd", "#d62728", "#8c564b", "#ff7f0e"]
    rates = {outcome: [] for outcome in outcomes}
    for level in levels:
        level_rows = [row for row in rows
                      if row["policy"] == "best_dqn" and row["level"] == level]
        for outcome in outcomes:
            rates[outcome].append(
                sum(row["outcome"] == outcome for row in level_rows) / len(level_rows)
            )
    fig, ax = plt.subplots(figsize=(7.2, 3.2))
    bottom = np.zeros(len(levels))
    for outcome, label, color in zip(outcomes, labels, colors):
        values = np.asarray(rates[outcome])
        ax.bar(range(len(levels)), values, bottom=bottom, label=label, color=color)
        bottom += values
    ax.set_xticks(range(len(levels)), ["L1", "L2", "L3", "L4", "L5", "L6"])
    ax.set(xlabel="Evaluation level", ylabel="Outcome rate", ylim=(0, 1))
    ax.legend(
        loc="upper left",
        bbox_to_anchor=(1.01, 1.0),
        borderaxespad=0,
        frameon=True,
        facecolor="white",
        edgecolor="#c7c7c7",
        framealpha=1.0,
        fontsize=7,
        ncol=1,
    )
    save(fig, "failure_modes")


